// tools/build-client.mjs — 把 src/*.mjs + catalog 数据 + client.js 打包成
// client/ 下三个文件，其中 bundle.js 是 the agent harness 真正加载的
// window.__ModuleLoader__.load({ id, factory }) CJS 包裹格式。
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const { loadDictionary } = await import('../src/load.mjs');
const { dict, problems } = loadDictionary(ROOT);
if (problems.length) { console.error('词典 lint 未通过：', problems); process.exitCode = 1; }

// 头像资产：DSH 只保证服务 /plugins/<id>/client.js，取不到包内静态图片，
// 所以位图必须 base64 内联进 bundle（同时天然满足「零网络请求」）。
const ASSET_DIR = join(ROOT, 'client', 'assets');
const ASSET_KEYS = ['calm', 'serious', 'thinking', 'sorry'];
const assets = {};
let assetBytes = 0;
for (const key of ASSET_KEYS) {
  const f = join(ASSET_DIR, `mascot-${key}.webp`);
  if (!existsSync(f)) continue;
  const buf = readFileSync(f);
  assetBytes += buf.length;
  assets[key] = `data:image/webp;base64,${buf.toString('base64')}`;
}
const assetsConst = 'const ASSETS = ' + JSON.stringify(assets) + ';';

writeFileSync(join(ROOT, 'client', 'gloss-assets.js'),
  '// GENERATED by tools/build-client.mjs — 请勿手改\n' +
  '// 头像以 data URI 内联，运行时不发起任何网络请求\n' +
  'export const ASSETS = ' + JSON.stringify(assets, null, 2) + ';\n', 'utf8');
if (assetBytes) console.log(`头像内联：${ASSET_KEYS.filter((k) => assets[k]).length} 张 / ${(assetBytes / 1024).toFixed(1)} KB`);


const data = {
  schemaVersion: dict.schemaVersion,
  dshVersionRange: dict.dshVersionRange,
  version: dict.version,
  entries: dict.entries,
  fallback: dict.fallback,
  locales: dict.locales,
};
const dataConst = 'const GLOSS_DATA = ' + JSON.stringify(data, null, 2) + ';';

// --- 1) 纯 ESM 数据 / 引擎（供 Node 自测与 smoke 使用） ---
writeFileSync(join(ROOT, 'client', 'gloss-data.js'),
  '// GENERATED by tools/build-client.mjs — 请勿手改\n' +
  'export const GLOSS_DATA = ' + JSON.stringify(data, null, 2) + ';\n', 'utf8');

// --- 2) 剥离 import/export，得到可内联的函数体 ---
const strip = (code) => code
  .replace(/^\s*import\s+.*?from\s+['"].*?['"];?\s*$/gm, '')
  .replace(/^\s*export\s*\{[^}]*\};?\s*$/gm, '')
  .replace(/^export\s+(function|const|class|let|var)\s/gm, '$1 ')
  .trim();

const order = ['redact.mjs', 'match.mjs', 'resolve.mjs', 'chain.mjs'];
const engineParts = order.map((f) => `//#region ${f}\n${strip(readFileSync(join(ROOT, 'src', f), 'utf8'))}\n//#endregion`);
const engineExports = [
  'redact', 'hashMessage', 'normalizeMessage', 'isSafePattern', 'matchEntry', 'lintDictionary',
  'mergeUserEntries', 'resolveError', 'renderShort', 'renderDetail', 'makeT', 'aggregateChain',
];
writeFileSync(join(ROOT, 'client', 'gloss-engine.js'),
  '// GENERATED by tools/build-client.mjs — 请勿手改\n' +
  '// 零依赖纯函数引擎，与 src/ 同源\n\n' +
  dataConst + '\n\n' + engineParts.join('\n\n') + '\n\nexport { ' + engineExports.join(', ') + ' };\n', 'utf8');

// --- 3) 适配层：取 client.js 的 ESM 源，剥掉 import/export ---
const adapter = strip(readFileSync(join(ROOT, 'client', 'client.js'), 'utf8'));

// --- 4) 真正的 client bundle：__ModuleLoader__ CJS 包裹 ---
const bundle = `// GENERATED by tools/build-client.mjs — 请勿手改
// the agent harness client bundle：与原生日志一致的 __ModuleLoader__.load 格式
window.__ModuleLoader__.load({
  id: "dsh-error-gloss",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

    let react;
    try { react = require("react"); } catch { react = null; }

${dataConst.split('\n').map((l) => '    ' + l).join('\n')}

${assetsConst.split('\n').map((l) => '    ' + l).join('\n')}

${engineParts.join('\n\n').split('\n').map((l) => '    ' + l).join('\n')}

${adapter.split('\n').map((l) => '    ' + l).join('\n')}

    // react 由基座提供；apply 内若 ctx.React 存在则覆盖
    if (react) hostReact = react;

    exports.name = NS;
    exports.NS = NS;
    exports.zh = zh;
    exports.en = en;
    exports.apply = apply;
    exports.inject = inject;
    exports.scanTurn = scanTurn;
    exports.ASSETS = ASSETS;
    exports.sameScan = sameScan;
    return module.exports;
  }
});
`;
writeFileSync(join(ROOT, 'client', 'bundle.js'), bundle, 'utf8');

console.log(`built: gloss-data.js / gloss-engine.js / bundle.js (${dict.entries.length} entries)`);
